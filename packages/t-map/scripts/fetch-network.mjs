// Reads every subway and light-rail stop from the MBTA V3 API and writes src/generated/network.ts.
// Run: pnpm --filter @questline/t-map fetch   (no API key needed at this volume)
//
// The API's canonical route patterns give each line's stops in order. Two things the API
// cannot say on its own are kept here, each with its source:
//   CLOSED      stops that no longer exist, still listed in the canonical pattern
//   SUSPENDED   stops that exist but are shut for a long project
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const BASE = "https://api-v3.mbta.com";
const ROUTES = ["Red", "Mattapan", "Orange", "Blue", "Green-B", "Green-C", "Green-D", "Green-E"];

/** MBTA alert, Nov 2026: "Fairbanks Street Station permanently closed as of November 7", merged into Brandon Hall. */
const CLOSED = new Set(["place-fbkst"]);
/** MBTA alert, Nov 2026: Symphony "is closed for major accessibility upgrades... expected to reopen in 2029". */
const SUSPENDED = { "place-symcl": "Closed for construction until 2029" };

async function get(path, params) {
  const url = new URL(path, BASE);
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, v);
  const res = await fetch(url, { headers: { accept: "application/vnd.api+json" } });
  if (!res.ok) throw new Error(`${url} -> ${res.status}`);
  return res.json();
}

const stops = new Map();
const routes = [];
for (const id of ROUTES) {
  const doc = await get("/route_patterns", {
    "filter[route]": id,
    "filter[canonical]": "true",
    include: "representative_trip.stops.parent_station,route",
  });
  const inc = new Map(doc.included.map((x) => [`${x.type}:${x.id}`, x]));
  const route = inc.get(`route:${id}`).attributes;
  const patterns = [];
  for (const p of doc.data) {
    if (p.attributes.direction_id !== 0) continue;
    const trip = inc.get(`trip:${p.relationships.representative_trip.data.id}`);
    const parents = trip.relationships.stops.data.map((s) => inc.get(`stop:${s.id}`).relationships.parent_station.data?.id);
    // A replacement bus pattern has kerbside stops with no parent station: not the line itself.
    if (parents.some((x) => !x)) continue;
    for (const pid of parents) {
      const a = inc.get(`stop:${pid}`).attributes;
      if (!stops.has(pid)) {
        stops.set(pid, {
          mbtaId: pid,
          name: a.name,
          lat: a.latitude,
          lon: a.longitude,
          accessible: a.wheelchair_boarding === 1,
          town: a.municipality,
          ...(SUSPENDED[pid] ? { suspended: SUSPENDED[pid] } : {}),
        });
      }
    }
    patterns.push({ name: p.attributes.name, stops: parents.filter((x) => !CLOSED.has(x)) });
  }
  routes.push({ id, name: route.long_name, color: `#${route.color}`, ends: route.direction_destinations, patterns });
}
for (const id of CLOSED) stops.delete(id);

const sorted = [...stops.values()].sort((a, b) => a.mbtaId.localeCompare(b.mbtaId));
const out = `// GENERATED by scripts/fetch-network.mjs from the MBTA V3 API. Do not edit by hand.
// Fetched ${new Date().toISOString().slice(0, 10)}. ${sorted.length} stations on ${routes.length} routes.

export interface RawStop {
  mbtaId: string;
  name: string;
  lat: number;
  lon: number;
  /** MBTA wheelchair_boarding = 1. */
  accessible: boolean;
  town: string;
  /** Present when the station is shut for a long project. */
  suspended?: string;
}
export interface RawRoute {
  id: string;
  name: string;
  color: string;
  /** Direction 0 and direction 1 destinations. */
  ends: string[];
  /** Direction 0 stop order, one entry per branch. */
  patterns: { name: string; stops: string[] }[];
}

export const RAW_STOPS: RawStop[] = ${JSON.stringify(sorted, null, 2)};

export const RAW_ROUTES: RawRoute[] = ${JSON.stringify(routes, null, 2)};
`;
const file = fileURLToPath(new URL("../src/generated/network.ts", import.meta.url));
writeFileSync(file, out);
console.log(`${sorted.length} stations, ${routes.length} routes -> ${file}`);
for (const r of routes) console.log(` ${r.id}: ${r.patterns.map((p) => `${p.name} (${p.stops.length})`).join(", ")}`);
